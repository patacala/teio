/** "Jun 5" from a date-only "YYYY-MM-DD" string, read in local time (no UTC shift). */
export function formatDateShort(iso: string): string {
  const [y, m, d] = iso.split('-').map(Number);
  return new Date(y, m - 1, d).toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
}

export function toISODate(d: Date): string {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

/**
 * Parses "YYYY-MM-DD" into a local date. `new Date("YYYY-MM-DD")` would read
 * it as UTC midnight, which local getters show as the previous day anywhere
 * behind UTC.
 */
export function fromISODate(s: string): Date {
  const [y, m, d] = s.split('-').map(Number);
  return new Date(y, m - 1, d);
}
